def predict_next_move(board: chess.Board, model: nn.Module, top_k: int = 3):
    """
    Predicts the best legal moves for a given board state by masking out
    all illegal moves in the 4096 action space before applying Softmax.
    """
    model.eval()
    state_tensor = torch.tensor(
        board_to_tensor(board), dtype=torch.float32
    ).unsqueeze(0).to(device)

    with torch.no_grad():
        logits = model(state_tensor).squeeze(0)  # Shape: (4096,)

    # Create a mask filled with -inf for illegal moves
    legal_mask = torch.full((4096,), float("-inf"), device=device)
    legal_moves_dict = {}

    for move in board.legal_moves:
        idx = encode_move(move)
        legal_mask[idx] = 0.0
        legal_moves_dict[idx] = move

    # Apply mask and calculate probabilities
    masked_logits = logits + legal_mask
    probabilities = torch.softmax(masked_logits, dim=0)

    # Extract top-k legal moves
    k = min(top_k, len(legal_moves_dict))
    top_probs, top_indices = torch.topk(probabilities, k)

    candidates = []
    for prob, idx in zip(top_probs, top_indices):
        move_obj = legal_moves_dict[idx.item()]
        candidates.append((move_obj.uci(), board.san(move_obj), prob.item() * 100))

    return candidates


