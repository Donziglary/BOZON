class BozonChessDataset(Dataset):
    def __init__(self, pgn_text: str):
        states, labels = [], []
        pgn_io = io.StringIO(pgn_text)

        while True:
            game = chess.pgn.read_game(pgn_io)
            if game is None:
                break
            board = game.board()
            for move in game.mainline_moves():
                states.append(board_to_tensor(board))
                labels.append(encode_move(move))
                board.push(move)

        self.states = torch.tensor(np.array(states), dtype=torch.float32)
        self.labels = torch.tensor(np.array(labels), dtype=torch.long)

    def __len__(self) -> int:
        return len(self.states)

    def __getitem__(self, idx: int):
        return self.states[idx], self.labels[idx]


dataset = BozonChessDataset(SAMPLE_PGN)
dataloader = DataLoader(dataset, batch_size=16, shuffle=True)

print(f"[INFO] Dataset created successfully. Total samples: {len(dataset)}")

