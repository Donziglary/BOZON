def board_to_tensor(board: chess.Board) -> np.ndarray:
    """Converts a chess.Board into a (14, 8, 8) float32 tensor."""
    tensor = np.zeros((14, 8, 8), dtype=np.float32)
    for square, piece in board.piece_map().items():
        row = 7 - (square // 8)
        col = square % 8
        channel = piece.piece_type - 1 + (6 if piece.color == chess.BLACK else 0)
        tensor[channel, row, col] = 1.0

    if board.turn == chess.WHITE:
        tensor[12, :, :] = 1.0

    for move in board.legal_moves:
        to_sq = move.to_square
        tensor[13, 7 - (to_sq // 8), to_sq % 8] = 1.0

    return tensor


def encode_move(move: chess.Move) -> int:
    """Encodes a chess.Move into an index [0, 4095]."""
    return move.from_square * 64 + move.to_square


def decode_move(index: int, board: chess.Board) -> chess.Move:
    """Decodes an index [0, 4095] back into a legal chess.Move."""
    from_sq = index // 64
    to_sq = index % 64
    piece = board.piece_at(from_sq)
    promotion = None
    if piece and piece.piece_type == chess.PAWN:
        if (piece.color == chess.WHITE and chess.square_rank(to_sq) == 7) or \
           (piece.color == chess.BLACK and chess.square_rank(to_sq) == 0):
            promotion = chess.QUEEN
    return chess.Move(from_sq, to_sq, promotion=promotion)

