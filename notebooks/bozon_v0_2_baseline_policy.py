class BozonBaselineNet(nn.Module):
    """
    Baseline Convolutional Neural Network for move prediction.
    Input: (Batch, 14, 8, 8)
    Output: (Batch, 4096) raw logits
    """
    def __init__(self):
        super().__init__()
        self.conv_block = nn.Sequential(
            nn.Conv2d(14, 64, kernel_size=3, padding=1),
            nn.BatchNorm2d(64),
            nn.ReLU(),
            nn.Conv2d(64, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(),
            nn.Conv2d(128, 128, kernel_size=3, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU()
        )

        self.fc_head = nn.Sequential(
            nn.Flatten(),
            nn.Linear(128 * 8 * 8, 1024),
            nn.ReLU(),
            nn.Dropout(p=0.2),
            nn.Linear(1024, 4096)
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        features = self.conv_block(x)
        logits = self.fc_head(features)
        return logits


model = BozonBaselineNet().to(device)
total_params = sum(p.numel() for p in model.parameters() if p.requires_grad)

print("[INFO] BozonBaselineNet initialized.")
print(f"[DEBUG] Trainable Parameters: {total_params:,}")

# ==============================================================================
# BLOCK 4: TRAINING LOOP AND WEIGHT SAVING
# ==============================================================================
criterion = nn.CrossEntropyLoss()
optimizer = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
epochs = 15

print("[INFO] Starting training process...")

for epoch in range(1, epochs + 1):
    model.train()
    running_loss = 0.0
    correct_predictions = 0
    total_samples = 0

    for states, labels in dataloader:
        states, labels = states.to(device), labels.to(device)

        optimizer.zero_grad()
        logits = model(states)
        loss = criterion(logits, labels)
        loss.backward()
        optimizer.step()

        running_loss += loss.item() * states.size(0)
        preds = torch.argmax(logits, dim=1)
        correct_predictions += (preds == labels).sum().item()
        total_samples += states.size(0)

    epoch_loss = running_loss / total_samples
    epoch_acc = (correct_predictions / total_samples) * 100

    if epoch == 1 or epoch % 5 == 0 or epoch == epochs:
        print(f"[TRAIN] Epoch {epoch:02d}/{epochs:02d} | Loss: {epoch_loss:.4f} | Accuracy: {epoch_acc:.2f}%")

